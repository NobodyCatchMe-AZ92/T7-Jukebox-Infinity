"""Generate src/font_cover.hpp: which characters the menu font (Frutiger) and the game's Japanese / Chinese fallback
fonts can draw, from the game's own font library (code points only - no glyph data). Non-Latin song names (user,
2026-11-14: a Japanese mp3 name showed white boxes) are drawn with a fallback font via <font face>.
  gen_font_cover.py <extracted gfxfontlib.uasset> <out .hpp>"""
import struct, sys

MAIN, GOTHIC, HEI = "Frutiger Neue LT Pro CnRegular", "BNSUCGothictk7CS M", "BNSFZLanTingHeiLBIG5tk7CS Regular"


def fonts(path):
    d = open(path, "rb").read()
    s = d[d.find(b"GFX\x0c"):]
    n = s[8] >> 3
    p = 8 + (5 + 4 * n + 7) // 8 + 4
    out = {}
    while p < len(s):
        h = struct.unpack_from("<H", s, p)[0]; p += 2
        code, ln = h >> 6, h & 63
        if ln == 63:
            ln = struct.unpack_from("<I", s, p)[0]; p += 4
        b = s[p:p + ln]
        if code == 75:  # DefineFont3
            fid, flags, lang, nl = struct.unpack_from("<HBBB", b, 0)
            name = b[5:5 + nl].rstrip(b"\0").decode()
            q = 5 + nl
            ng = struct.unpack_from("<H", b, q)[0]; q += 2
            w = 4 if flags & 0x08 else 2
            ct = struct.unpack_from("<I" if w == 4 else "<H", b, q + ng * w)[0]
            out[name] = set(struct.unpack_from("<%dH" % ng, b, q + ct))
        elif code == 0:
            break
        p += ln
    return out


def ranges(codes):
    r, c = [], sorted(codes)
    for x in c:
        if r and r[-1][1] == x - 1:
            r[-1][1] = x
        else:
            r.append([x, x])
    return r


f = fonts(sys.argv[1])
main, goth, hei = f[MAIN], f[GOTHIC], f[HEI]
hei_only = hei - goth - main
lines = ["// GENERATED by tools/gen_font_cover.py from the game's gfxfontlib (code points only).",
         "// Which characters each font can draw: the menu font, then the fallbacks used via <font face> for the rest. The",
         "// faces are the font library's class names (SymbolClass) - the names the game's movies use.",
         "#pragma once", "#include <cstdint>", "", "namespace jb::fontcover {",
         'inline constexpr const char *kGothic = "$UCGothic_M"; // %s: Japanese / Korean / Cyrillic' % GOTHIC,
         'inline constexpr const char *kHei = "$UCGothicBIG5_M"; // %s: Chinese' % HEI,
         "struct Range", "{", "\tuint16_t lo, hi;", "};"]
for var, codes in (("kMain", main), ("kGothicCover", goth - main), ("kHeiCover", hei_only)):
    rs = ranges(codes)
    lines.append("inline constexpr Range %s[] = { // %d characters in %d ranges" % (var, len(codes), len(rs)))
    row = []
    for lo, hi in rs:
        row.append("{0x%04X,0x%04X}" % (lo, hi))
        if len(row) == 8:
            lines.append("\t" + ",".join(row) + ","); row = []
    if row:
        lines.append("\t" + ",".join(row) + ",")
    lines.append("};")
lines += ["template <size_t N> inline bool in(const Range (&r)[N], uint32_t c)", "{",
          "\tsize_t lo = 0, hi = N;", "\twhile (lo < hi)", "\t{", "\t\tsize_t m = (lo + hi) / 2;",
          "\t\tif (c < r[m].lo)", "\t\t\thi = m;", "\t\telse if (c > r[m].hi)", "\t\t\tlo = m + 1;", "\t\telse",
          "\t\t\treturn true;", "\t}", "\treturn false;", "}",
          "// 0 = the menu font, 1 = Gothic, 2 = Hei (characters no font has stay with the menu font)",
          "inline int font_for(uint32_t c)", "{", "\tif (c < 0x80 || in(kMain, c))", "\t\treturn 0;",
          "\tif (in(kGothicCover, c))", "\t\treturn 1;", "\treturn in(kHeiCover, c) ? 2 : 0;", "}",
          "} // namespace jb::fontcover", ""]
open(sys.argv[2], "w", encoding="utf-8", newline="\r\n").write("\n".join(lines))
print("main %d, gothic extra %d, hei extra %d" % (len(main), len(goth - main), len(hei_only)))
