"""Generate src/export_media.hpp: the game .wem behind each "bgm:<id>" song of the Tekken 7 list (for L3 export,
user 2026-11-14). Input: bgm_states.py output (state -> media, plus "selector children" for menu-type selectors).
Where a song has more than one media (an intro + its loop), the largest file is taken.
  gen_export_media.py <bgm_map.txt> <paks dir> <out .hpp>"""
import glob, os, re, sys
sys.path.insert(0, os.path.dirname(__file__))
import paklist

lines = open(sys.argv[1], encoding="utf-8").read().splitlines()
sizes = {}
for pak in glob.glob(os.path.join(sys.argv[2], "pakchunk*.pak")):
    for name, off, size, usize, comp in paklist.entries(pak):
        b = name.rsplit("/", 1)[-1]
        if b.endswith(".wem") and b[:-4].isdigit():
            sizes.setdefault(int(b[:-4]), usize)
children = {}
for l in lines:
    m = re.match(r"  (\S+) \d+ type \d+ sub-states \[\] media \[([\d, ]*)\]", l)
    if m:
        children.setdefault(m.group(1), []).extend(int(x) for x in m.group(2).split(",") if x.strip())
out = {}
for l in lines:
    m = re.match(r"(\d+) (\S+) (\S+) -> \[([\d, ]+)\]", l)
    if m:
        out[int(m.group(1))] = [int(x) for x in m.group(4).split(",")]
        continue
    m = re.match(r"(\d+) (\S+) (\S+) -> selector in bank", l)
    if m and m.group(2) in children:
        out[int(m.group(1))] = children[m.group(2)]
rows = []
for bid in sorted(out):
    media = [x for x in out[bid] if x in sizes] or out[bid]
    best = max(media, key=lambda x: sizes.get(x, 0))
    rows.append((bid, best, sizes.get(best, 0)))
with open(sys.argv[3], "w", encoding="utf-8", newline="\r\n") as f:
    f.write("// GENERATED by tools/gen_export_media.py (bank dump + BGM table rows, 2026-11-14): the game .wem behind each\n")
    f.write("// \"bgm:<id>\" song, for L3 export (user, 2026-11-14). { bgm id, media id }\n#pragma once\n#include <cstdint>\n\n")
    f.write("namespace jb {\nstruct ExportMedia\n{\n\tint bgm;\n\tuint32_t media;\n};\ninline const ExportMedia kExportMedia[] = {\n")
    for bid, best, sz in rows:
        f.write("\t{ %d, %d }, // %.1f MB\n" % (bid, best, sz / 1e6))
    f.write("};\ninline uint32_t export_media(int bgm)\n{\n\tfor (auto &e : kExportMedia)\n\t\tif (e.bgm == bgm)\n\t\t\treturn e.media;\n\treturn 0;\n}\n} // namespace jb\n")
print(len(rows), "songs;", sum(1 for r in rows if not r[2]), "without a file")
